import itertools

personas = ['Ana', 'Bruno', 'Carla', 'Diego']

# Todos los posibles repartos de regalos
todos_repartos = list(itertools.permutations(personas))

# Casos favorables: nadie recibe su propio regalo (pos_persona != regalo)
casos_favorables = [
    reparto for reparto in todos_repartos
    if all(reparto[i] != personas[i] for i in range(len(personas)))
]

probabilidad = len(casos_favorables) / len(todos_repartos)

print("\n--- EJERCICIO 5 ---")
