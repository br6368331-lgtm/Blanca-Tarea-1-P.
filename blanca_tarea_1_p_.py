import random

def probabilidad_suma_dados(num_simulaciones=100000):
    exitos = 0
    for _ in range(num_simulaciones):
        dado1 = random.randint(1, 6)
        dado2 = random.randint(1, 6)
        if dado1 + dado2 == 5:
            exitos += 1
    return exitos / num_simulaciones

prob_estimada = probabilidad_suma_dados()
print(f"Probabilidad teórica: 4/36 = {4/36:.4f}")
print(f"Probabilidad simulada (Monte Carlo): {prob_estimada:.4f}")

import itertools

# Generar todas las combinaciones posibles de 3 dígitos con reposición (del 0 al 9)
total_contrasenias = 10 ** 3

# Casos favorables: permutaciones de 10 elementos tomados de 3 en 3
# len(set(c)) == 3 asegura que los 3 dígitos sean únicos (sin repetición)
casos_favorables = sum(1 for c in itertools.product(range(10), repeat=3) if len(set(c)) == 3)

probabilidad = casos_favorables / total_contrasenias
print(f"Casos totales: {total_contrasenias}")
print(f"Casos favorables: {casos_favorables}")
print(f"Probabilidad exacta: {probabilidad:.4f}")

